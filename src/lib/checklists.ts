export const CHECKLISTS: Checklist[] = [
  YOUTUBER_TAX_2026,
  YOUTH_CULTURE_PASS_2026,
  RESIGNATION_30D,
];

export function getChecklist(slug: string): Checklist | undefined {
  return CHECKLISTS.find((c) => c.slug === slug);
}

export function totalChecklistCount(): number {
  return CHECKLISTS.length;
}

export function checklistItemCount(checklist: Checklist): number {
  return checklist.sections.reduce((sum, s) => sum + s.items.length, 0);
}

export function checklistImportantCount(checklist: Checklist): number {
  return checklist.sections.reduce(
    (sum, s) => sum + s.items.filter((i) => i.important).length,
    0,
  );
}

export function daysUntil(deadline: string): number | null {
  const target = new Date(deadline + "T23:59:59+09:00").getTime();
  const now = Date.now();
  if (Number.isNaN(target)) return null;
  return Math.ceil((target - now) / (1000 * 60 * 60 * 24));
}

